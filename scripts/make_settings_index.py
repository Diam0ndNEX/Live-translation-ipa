#!/usr/bin/env python3
"""Builds App/UI/Model/SettingsSearchIndex.swift: every setting's label and the page it lives on, so Settings search
finds the setting itself (spec §13.5.5). Run after changing a settings page; `--check` fails if the file is stale."""
import re
import sys
from pathlib import Path
from sources import read_source

root = Path(__file__).resolve().parents[1]
# Source names, not paths: sources.py finds each file (and any Name+Topic.swift parts) wherever it lives.
NAMES = ["SettingsViews", "SettingsCategories", "CustomizationViews", "ExperimentalFeaturesView"]
# Page struct -> (enum case, title shown under the result)
PAGES = {
    "ReadingSettings": ("reading", "Area and recognition"),
    "IntelligenceSettings": ("textRules", "Text rules and names"),
    "ResponsivenessSettings": ("timing", "Timing"),
    "WindowSettings": ("window", "Window"),
    "CaptionAppearanceSettings": ("style", "Style"),
    "InterfaceSettings": ("appearance", "Appearance"),
    "FeedbackStorageSettings": ("feedback", "Haptics and feedback"),
    "ReaderWorkspaceSettings": ("reader", "Reader and photos"),
    "PerformanceSettings": ("performance", "Performance and battery"),
    "PrivacySettings": ("privacy", "Privacy"),
    "HistoryStorageSettings": ("history", "History and storage"),
    "BackupSettings": ("backup", "Backup and reset"),
    "TranslationSettings": ("system", "System"),
    "DiagnosticsSettingsPage": ("diagnostics", "Diagnostics settings"),
    "DiagnosticsCollectionControls": ("diagnostics", "Diagnostics settings"),
    "ExperimentalFeaturesView": ("experimental", "Experimental features"),
}
LABEL = re.compile(r'(?:Toggle|Picker|Stepper)\(\s*"([^"\\]{3,70})"|LabeledToggleRow\(title:\s*"([^"\\]{3,70})"'
                   r'|ExperimentalOption\(\s*title:\s*"([^"\\]{3,70})"|accessibilityLabel\("([^"\\]{3,70})"\)')


def entries():
    out = []
    for f in NAMES:
        s = read_source(f)
        for m in re.finditer(r"\n(?:private )?struct (\w+): View \{", s):
            name = m.group(1)
            if name not in PAGES:
                continue
            start = m.end()
            nxt = re.search(r"\n(?:private )?struct \w+", s[start:])
            body = s[start:start + nxt.start()] if nxt else s[start:]
            for lm in LABEL.finditer(body):
                label = next(g for g in lm.groups() if g)
                out.append((label, *PAGES[name]))
    seen, unique = set(), []
    for e in out:
        if (e[0], e[1]) not in seen:
            seen.add((e[0], e[1]))
            unique.append(e)
    return sorted(unique, key=lambda e: (e[1], e[0].lower()))


def render(items):
    cases = sorted({c for _, c, _ in items} | {c for c, _ in PAGES.values()})
    lines = ["// ScreenLingo – App – Settings search index (2.1.0, spec §13.5.5)",
             "// GENERATED by scripts/make_settings_index.py from the settings pages. Do not edit by hand.",
             "import Foundation", "",
             "enum SettingsPage: String, CaseIterable {",
             "    case " + ", ".join(cases),
             "}", "",
             "struct SettingsSearchEntry: Identifiable {",
             "    let label: String",
             "    let page: SettingsPage",
             "    let pageTitle: String",
             "    var id: String { page.rawValue + \"|\" + label }",
             "}", "",
             "enum SettingsSearchIndex {",
             "    static let all: [SettingsSearchEntry] = ["]
    for label, case, title in items:
        lines.append(f'        SettingsSearchEntry(label: "{label}", page: .{case}, pageTitle: "{title}"),')
    lines += ["    ]", "",
              "    static func matches(_ query: String) -> [SettingsSearchEntry] {",
              "        let q = query.trimmingCharacters(in: .whitespaces)",
              "        guard q.count >= 2 else { return [] }",
              "        return all.filter { $0.label.localizedCaseInsensitiveContains(q) }",
              "    }", "}", ""]
    return "\n".join(lines)


target = root / "App/UI/Model/SettingsSearchIndex.swift"
text = render(entries())
if "--check" in sys.argv:
    if not target.exists() or target.read_text() != text:
        print("Settings search index is stale: run python3 scripts/make_settings_index.py")
        sys.exit(1)
    print(f"Settings search index is current ({text.count('SettingsSearchEntry(label')} settings)")
else:
    target.write_text(text)
    print(f"Wrote {target.relative_to(root)} with {text.count('SettingsSearchEntry(label')} settings")
